from __future__ import annotations

import contextlib
import io
import json
import tempfile
import unittest
import zipfile
from pathlib import Path

from adapter_archive import pack_adapter
from adapter_runtime import load_adapter, _asset_root
import runner


class AdapterArchiveTest(unittest.TestCase):
    def test_cli_export_roundtrips_declarations_and_prefers_package_sql(self):
        with tempfile.TemporaryDirectory(prefix="jdbc-adapter-export-") as directory:
            root = Path(directory)
            archive = root / "adapter.zip"
            original = load_adapter(runner.PROJECT_ROOT, "examples/adapters/postgresql-local")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(0, runner.main(["pack-adapter", "--adapter",
                    str(original.root), "--output", str(archive)]))
                self.assertEqual(2, runner.main(["pack-adapter", "--adapter",
                    str(original.root), "--output", str(archive)]))
            with zipfile.ZipFile(archive) as package:
                self.assertNotIn(".env", package.namelist())
                self.assertFalse(any(name.endswith(".jar") for name in package.namelist()))
                package.extractall(root / "extracted")  # archive generated by this test only
            imported = load_adapter(runner.PROJECT_ROOT, str(root / "extracted"))
            self.assertEqual(original.manifest, imported.manifest)
            self.assertEqual((root / "extracted" / "ddl").resolve(),
                _asset_root(runner.PROJECT_ROOT, imported.root, "ddl"))

    def test_explicit_external_roots_are_normalized_without_overwriting(self):
        with tempfile.TemporaryDirectory(prefix="jdbc-adapter-external-") as directory:
            root = Path(directory)
            manifest = json.loads((runner.PROJECT_ROOT / "examples/adapters/postgresql-local/adapter.json").read_text())
            for kind in ("ddl", "dml", "pool"):
                manifest["assets"][kind] = str(runner.PROJECT_ROOT / kind)
            (root / "adapter.json").write_text(json.dumps(manifest))
            archive = root / "portable.zip"
            pack_adapter(runner.PROJECT_ROOT, str(root), archive)
            with zipfile.ZipFile(archive) as package:
                exported = json.loads(package.read("adapter.json"))
                for kind in ("ddl", "dml", "pool"):
                    self.assertEqual(kind, exported["assets"][kind])
                self.assertEqual(manifest["capabilities"], exported["capabilities"])
                self.assertEqual(manifest["identity"], exported["identity"])
                self.assertIn("pool/postgresql.yaml", package.namelist())
            original_bytes = archive.read_bytes()
            with self.assertRaises(FileExistsError):
                pack_adapter(runner.PROJECT_ROOT, str(root), archive)
            self.assertEqual(original_bytes, archive.read_bytes())

    def test_sql_symlink_escape_is_rejected(self):
        with tempfile.TemporaryDirectory(prefix="jdbc-adapter-symlink-") as directory:
            root = Path(directory)
            package = root / "package"
            package.mkdir()
            manifest = json.loads((runner.PROJECT_ROOT / "examples/adapters/postgresql-local/adapter.json").read_text())
            # Reuse regular assets except an explicitly separate synthetic SQL directory.
            import shutil
            shutil.copytree(runner.PROJECT_ROOT / "ddl/postgresql", package / "ddl/postgresql")
            (package / "ddl/postgresql/escape.sql").symlink_to(root / "outside.sql")
            (root / "outside.sql").write_text("-- synthetic external file")
            (package / "adapter.json").write_text(json.dumps(manifest))
            with self.assertRaisesRegex(ValueError, "ADAPTER_RESOURCE_PATH_INVALID"):
                pack_adapter(runner.PROJECT_ROOT, str(package), root / "bad.zip")
            self.assertFalse((root / "bad.zip").exists())
